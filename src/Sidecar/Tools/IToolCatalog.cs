namespace Sidecar;

/// <summary>
/// 工具輪盤的圖示。**由程式繪製的線稿**，不引入圖片資源（本專案目前沒有圖示資產，
/// 而設定頁已經立下「XAML 內 0 個硬編碼色、0 個文字字面值」的紀律；
/// 引進一張 PNG 會同時破壞配色唯一權威與離線不變式）。
/// </summary>
internal enum ToolIcon
{
    /// <summary>順時針 90 度的轉向箭頭（兩個弧形箭頭）。</summary>
    Rotate90,

    /// <summary>
    /// 被劃掉的中繼資料標籤（tag）——「把檔案裡那些看不見的標籤去掉」。
    /// 選這個形狀是因為 EXIF／ICC／文字註解在容器裡是**同一種東西**（掛在影像資料外的區段），
    /// 而 17px 的線稿畫不了「三種各畫一個」；標籤＋斜線是唯一一個能在這個尺寸辨識的形狀。
    /// </summary>
    StripMetadata,

    /// <summary>
    /// 兩個相向的箭頭——「把兩邊往中間壓」。這是「壓縮／縮小」在線稿圖示裡的通用寫法
    /// （兩個半箭頭指向同一點），而且與既有的兩顆一眼可分：
    /// 旋轉是**弧線**、去中繼資料是**多邊形＋斜線**、壓縮是**直的**且左右對稱。
    ///
    /// 為什麼不是「一個箱子 ＋ 四支往內的箭頭」那種更像字典圖示的畫法：17px 之下
    /// 四個箭頭會黏成一團，而扇區只有 80×24px 的空間（見 <see cref="WheelDesign.ToolIconPx"/>）。
    /// 為什麼不是填色的實心三角形：扇區上的圖示一律是**同一支線稿筆**（見
    /// <c>WheelPresenter.DrawToolIcon</c>），實心塊會比另外兩顆重一個級別。
    /// </summary>
    Compress,

    /// <summary>
    /// 裁切（M3 第四顆扇形，工具 id `crop`）：一個**斜的裁切框**——四邊的虛線角標 ＋ 兩條對角線。
    ///
    /// 為什麼是這個形狀：17px 之下要與既有三顆一眼可分。既有三顆佔掉的形狀是
    /// 弧線（旋轉）、多邊形＋斜線（去中繼資料）、上下對稱的直線（壓縮），
    /// 唯一還沒被用掉、而且在這個尺寸撐得住的辨識特徵是**「一個框 ＋ 框上的兩個角」**。
    /// 刻意**不畫實心遮罩**（那會變成一片糊），也刻意不用四角的 L 形把手（四個 L 在 17px 下
    /// 會與標籤的多邊形撞形）。對角線是「這是選取範圍」在線稿裡的老寫法。
    /// </summary>
    Crop,

    /// <summary>
    /// 讀 QR（M3 第五顆扇形，工具 id `read-qr`）：**三個角落的尋像圖案 ＋ 兩條對角線的資料點**——
    /// 也就是 QR 碼本身那個一眼可辨的骨架。
    ///
    /// 為什麼是這個形狀：17px 之下要與既有四顆一眼可分。前四顆佔掉的形狀是
    /// 弧線（旋轉）、多邊形＋斜線（去中繼資料）、上下對稱的直線（壓縮）、一個框＋對角線（裁切）。
    /// QR 的尋像圖案是**全世界唯一一個「一個方框裡再一個方框」的三點排列**，
    /// 而裁切那一顆只有**一個**框——兩者的辨識特徵因此不重疊（裁切的框是斜的且有角標，
    /// 讀 QR 是**正的三個**）。
    ///
    /// ⚠ 刻意**不畫成棋盤格**（那才是「資料區」，但 17px 下會糊成一團灰），
    /// 也刻意不用「相機鏡頭」那種圖示：本工具**不吃相機**，它讀的是已經在畫面上的圖，
    /// 畫一個鏡頭會承諾一件產品沒有做的事。
    /// </summary>
    ReadQr,

    /// <summary>
    /// 合併 PDF（M3 第六顆扇形，工具 id `merge-pdf`）：**左邊兩張小頁 ＋ 一條收束的線 ＋
    /// 右邊一張大頁**——「多份進去、一份出來」。
    ///
    /// 為什麼是這個形狀：17px 之下要與既有五顆一眼可分。前五顆佔掉的形狀是
    /// 弧線（旋轉）、多邊形＋斜線（去中繼資料）、上下對稱的直線（壓縮）、
    /// 一個框＋兩條對角線（裁切）、三個尋像圖案＋四個資料點（讀 QR）。
    /// 這五顆的共同點是**都是單一物件**；唯一還沒被用掉、而且在這個尺寸撐得住的辨識特徵是
    /// **「三個框 ＋ 一組收束的線」**（＝多 → 一），這正是這個工具唯一做的事。
    ///
    /// ⚠ 刻意**不畫「兩張紙疊在一起」**（那在 17px 下就是一團）也不用**書籤／迴紋針**
    /// 那一類「文件」的通用圖示：本工具**不保留書籤**（PDFsharp 的 `/Outlines` 不 deep-copy），
    /// 畫一個迴紋針或標籤會承諾一件產品沒有做的事（與 <see cref="ReadQr"/> 不畫鏡頭同一條規矩）。
    ///
    /// 刻意**不用箭頭**：箭頭在這個輪盤上已經是既有的形狀語彙所佔用的
    /// （<see cref="Rotate90"/> 的箭頭、<see cref="Compress"/> 的相向箭頭），再加一個只會更難分。
    /// 收束的線本身就有方向（左寬右窄），不需要另一個符號再說一次。
    /// </summary>
    MergePdf,

    /// <summary>
    /// 去背（M3 第七顆扇形，工具 id `remove-bg`）：**一個人的剪影 ＋ 框住他的四個角標**
    /// ——「把人從背景裡框出來」。
    ///
    /// 為什麼是這個形狀：17px 之下要與既有六顆一眼可分。前六顆佔掉的形狀是
    /// 弧線（旋轉）、多邊形＋斜線（去中繼資料）、上下對稱的直線（壓縮）、一個斜框＋兩條對角線（裁切）、
    /// 三個尋像圖案＋四個資料點（讀 QR）、三個框＋收束的線（合併）。
    /// 這六顆的共同點是**都不畫人／物**；唯一還沒被用掉、而且在這個尺寸撐得住的辨識特徵是
    /// **「一個填不滿的人形」**——圓頭 ＋ 梯形身，正是「這張圖裡的人」在線稿裡的通用寫法。
    ///
    /// 四個角標（不是一個完整的外框）刻意與 <see cref="Crop"/> 的「斜框＋對角線」分開：
    /// 裁切是**一個框在動**，這裡是**框不動、框裡的東西被留下**，所以這裡只畫四個角。
    /// 刻意**不畫成剪刀**：剪刀在這個尺寸下會與 <see cref="StripMetadata"/> 的斜線撞形，
    /// 而且它承諾的是「剪」，本工具做的是「把背景變透明」——留下的檔案與原圖同尺寸，
    /// 並沒有把任何東西剪掉。刻意**不用棋盤格**表示透明：那在 17px 下是一團糊
    /// （與 <see cref="ReadQr"/> 不畫棋盤格同一條理由）。
    /// </summary>
    RemoveBg
}

/// <summary>
/// 一個工具。扇區上畫的字是 <see cref="SectorLabel"/>（**跟著介面語言**，
/// 2026-10-21 起），而 <see cref="Label"/> 是**診斷用的穩定英文名**。
/// </summary>
/// <remarks>
/// 為什麼要有兩個名字、而不是把 <see cref="Label"/> 直接翻掉：<see cref="Label"/> 會進
/// `--tools-list` 的證據行，而驗收腳本拿它當斷言（`label='READ QR'`）。讓它跟著介面語言
/// 走，同一條斷言就會因為跑測試那台機器的系統語言而紅——診斷字串必須與語言無關，
/// 就像 <see cref="Id"/> 一樣。畫面上要什麼語言，是 <see cref="SectorLabel"/> 的事。
///
/// 歷史：原本的設計是「扇區一律大寫英文、不進 i18n」，理由是「80×24px 放中文會糊」。
/// 2026-10-21 實測後半句成立一半：寬度根本不是限制（最寬的英文 65px、韓文 53px，
/// 都遠小於 80px），真正的限制是 11px 下筆畫會黏在一起。所以現在改成本地化 +
/// **字級提到 12.7px** + 挑筆畫少的措辭（見 WheelDesign.LabelFontPx 的註解）。
/// </remarks>
/// <param name="Id">穩定識別碼。會進日誌與 worker 協議，**不得就地改字**（改了等於換一個工具）。</param>
/// <param name="Label">診斷用的穩定英文名（大寫）。**不跟介面語言走**，驗收腳本以它為斷言。</param>
/// <param name="DescriptionKey">圓心膠囊那句話的 <see cref="UiStrings"/> key（參考設計的「中心顯示 hover 動作」）。</param>
/// <param name="Icon">線稿圖示。</param>
internal sealed record ToolDescriptor(string Id, string Label, string DescriptionKey, ToolIcon Icon)
{
    /// <summary>
    /// 扇區上真的畫出來的那個字（**跟著介面語言**）。key 由 <see cref="Id"/> 推出來，
    /// 所以新增一顆工具時只要 id 定了，五張字表各補一個 <c>tool.label.&lt;id&gt;</c> 就好，
    /// 不必在兩個地方各寫一次字面值。
    /// </summary>
    public string SectorLabel => UiStrings.Get("tool.label." + Id);

    /// <summary>
    /// 圓心膠囊的一句話（**跟著介面語言**）。資料裡存的是 key，不是字面值：
    /// 這樣同一個工具在 zh-Hant 與 en 之間切換時不必重建目錄，也不會出現「兩份描述漂移」。
    /// </summary>
    public string Description => UiStrings.Get(DescriptionKey);
    /// <summary>
    /// 這個工具適不適用於某一個**來源格式**（`CodecRegistry.FormatOfPath` 回的那個名字）。
    ///
    /// **這是「適用性」的唯一判定處**，由 <see cref="ToolCatalog.ToolsFor"/> 呼叫；
    /// UI 不得自己判斷（<see cref="IToolCatalog"/> 立下的規矩：輪盤只拿到一排字串）。
    ///
    /// 為什麼掛在描述元上而不是寫在 <see cref="ToolCatalog.ToolsFor"/> 裡的一個 <c>if</c>：
    /// 「這一顆工具吃什麼」是**這一顆工具自己的知識**。寫在 ToolsFor 裡，新增工具的人會在
    /// 兩個地方各改一次，而漏改的那一半症狀是「扇形出現了、按下去只會失敗」——
    /// 畫面上有的東西必須是真的，所以判定要跟工具的身分放在一起。
    ///
    /// 預設回 <c>true</c>：前五顆工具（旋轉／去中繼資料／壓縮／裁切／讀 QR）對**所有**
    /// 「本產品支援的圖片」都成立，那不是「以後也一定如此」的宣告——真正的細條件會寫在
    /// 這裡，而 `merge-pdf` 已經是第一個例子（它只吃 PDF）。
    ///
    /// <para>
    /// ⚠ **`remove-bg`（第七顆）刻意走預設值，但這不是「沒想過」**（2026-10-08 裁定）：
    /// 它需要一個**外部模型檔**（`models\model_fp16.onnx`，不進版控），所以「模型不在」
    /// 的時候這一顆按下去會回一個具名的失敗。**為什麼仍然是預設值**：
    ///   ①<b>「已實作」的判準是「這個行程做不做得到這件事」，而它做得到</b>——缺的是
    ///     一個使用者一條命令就能補上的檔案，不是這個工具不存在（對照組：合併 PDF 對一張
    ///     JPEG 是**永遠**做不到，那才是 ApplicesTo 該擋的形狀）。
    ///   ②把「模型在不在」變成顯示條件＝把檔案系統狀態變成**第二份適用性規則**，
    ///     而它的症狀是最糟的那一種：扇形**時有時無**（使用者複製了模型之後要重開才有）。
    ///   ③失敗必須看得見：訊息直接指向 `tools\get-rembg-model.ps1`，使用者當場知道下一步。
    /// 「畫面上有的東西必須是真的」在這裡的兌現方式是**選了它會說真話**，不是把它藏起來。
    /// </para>
    /// </summary>
    public bool AppliesTo(PayloadVerdict verdict)
    {
        // 其餘六顆工具對「本產品支援的圖片」都成立。
        if (Id != ToolCatalog.MergePdfId) return true;

        // ① 整批都是 PDF ⇒ 適用（使用者 2026-10-07 裁定的產品語意）：整頁物件搬移，不重編碼。
        if (string.Equals(verdict.SourceFormat, "PDF", StringComparison.OrdinalIgnoreCase)) return true;

        // ② **圖片 ⇒ 至少兩張才適用**（2026-10-14 追加，使用者裁定「一次選多個圖檔」）。
        //    一張圖合成一份 PDF 沒有意義（而那件事已經有第一層的「圖片 → PDF」那條路），
        //    所以放行它就會出現一顆按下去只會失敗的扇形——正是這一段註解一開始要擋的東西。
        //    ⚠ `CanConvert` 問的是「這一批是不是可轉換類別（圖片）」，它由 `Classify` 填，
        //    判定知識仍然只有那一個地方；這裡**不得**自己列一份格式清單。
        return verdict.CanConvert && verdict.FileCount >= 2;
    }
}

/// <summary>
/// 工具知識的**唯一查詢介面**（規格 §9.4:390 的工具輪盤擴充點）。
///
/// 分工比照 <see cref="IFormatCatalog"/>：<see cref="WheelPresenter"/> 只拿到「一排字串」，
/// **不得自己判斷有哪些工具、也不得自己決定某一格能不能用**。工具的清單與適用性都屬於工具知識，
/// 只有這個介面說了算。
///
/// **只回已實作且適用的工具**：介面不得顯示還不能執行的工具。設定頁已經有「存得下但沒生效」
/// 的前例，那個教訓是「畫面上有的東西必須是真的」。
/// </summary>
internal interface IToolCatalog
{
    /// <summary>目前**已實作**的工具。順序即扇區順序（自正上方起、順時針）。</summary>
    IReadOnlyList<ToolDescriptor> Tools { get; }

    /// <summary>
    /// 這一批檔案適用的工具。拒絕語意沿用第一層（規格 §4.3）：不是 <see cref="PayloadStatus.Ready"/>
    /// 就一個工具都不給，呼叫端照既有規則顯示拒絕訊息。
    /// </summary>
    IReadOnlyList<ToolDescriptor> ToolsFor(PayloadVerdict verdict);
}
